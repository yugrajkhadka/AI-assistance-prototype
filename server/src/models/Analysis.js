import mongoose from 'mongoose'

const lightSchema = new mongoose.Schema({
  role: String,          // additional lights only: kicker, hair, background...
  type: String,          // display name: fixture + modifier
  fixture: String,
  modifier: String,
  motivation: String,
  position: String,      // short plain-English placement
  azimuthDeg: Number,    // overhead plan: 0 = lens axis, ±90 side, ±180 behind; negative = camera left
  elevationDeg: Number,  // 0 = eye level, 90 = overhead
  distanceM: Number,
  intensity: Number,
  colorTempK: Number,
  gel: String,
  color: String,         // display: "4300K, 1/8 plus green"
  notes: String,
}, { _id: false })

const shotSchema = new mongoose.Schema({
  type: String,
  description: String,
  lens: String,
  movement: String,
  angle: String,
  lighting: String,
  duration: String,
  status: { type: String, enum: ['approved', 'pending', 'revision'], default: 'pending' },
  locked: { type: Boolean, default: false },
  confidence: Number,
  intent: { type: String, enum: ['establish', 'detail', 'character', 'emotion', 'dialogue', 'thematic'] },
  completedOnSet: { type: Boolean, default: false },
  takes: { type: Number, default: 0 },
  notes: [{ text: String, author: String, createdAt: { type: Date, default: Date.now } }],
}, { timestamps: true })

const storyboardFrameSchema = new mongoose.Schema({
  shotIndex: Number,
  caption: String,
  style: { type: String, default: 'cinematic' },
  imagePrompt: String,
  // Pencil-style storyboard drawing generated by Claude (sanitized SVG markup).
  sketchSvg: String,
  sketchModel: String,
  sketchedAt: Date,
}, { _id: false })

const blockingCharacterSchema = new mongoose.Schema({
  name: String,
  start: { x: Number, y: Number },
  end: { x: Number, y: Number },
  movement: String,
}, { _id: false })

const blockingSchema = new mongoose.Schema({
  characters: [blockingCharacterSchema],
  camera: { x: Number, y: Number },
  notes: String,
}, { _id: false })

const sceneSchema = new mongoose.Schema({
  number: Number,
  title: String,
  description: String,
  mood: String,
  style: String,
  duration: String,
  characters: [String],
  locations: [String],
  props: [String],
  shots: [shotSchema],
  storyboard: [storyboardFrameSchema],
  lightingPlan: {
    applicable: { type: Boolean, default: true },
    reason: String,
    cameraWhiteBalanceK: Number,
    keyLight: lightSchema,
    fillLight: lightSchema,
    backLight: lightSchema,
    additionalLights: [lightSchema],
    // Older plans stored practicals as plain strings; new ones are objects.
    practicals: [mongoose.Schema.Types.Mixed],
    ratio: String,
    ratioNote: String,
    notes: String,
  },
  blocking: blockingSchema,
})

const cameraSettingsSchema = new mongoose.Schema({
  exposure: { value: String, min: String, max: String },
  iso: { value: Number, min: Number, max: Number },
  shutter: { value: String, angle: String },
  whiteBalance: { value: String, mode: String },
  nd: { value: String, stops: Number },
  lens: new mongoose.Schema({
    focal: String,
    type: String,
    mount: String,
    tStop: String,
  }, { _id: false }),
  resolution: String,
  frameRate: String,
  codec: String,
}, { _id: false })

const analysisSchema = new mongoose.Schema({
  project: { type: mongoose.Schema.Types.ObjectId, ref: 'Project', required: true, index: true },
  themes: [String],
  overallMood: String,
  suggestedStyle: String,
  confidenceScore: Number,
  sceneBreakdown: {
    total: Number,
    analyzed: Number,
    flagged: Number,
  },
  characterArcs: [{
    name: String,
    archetype: String,
    screenTime: String,
  }],
  ambiguities: [{
    scene: Number,
    note: String,
  }],
  // Recommended from the script during analysis; pre-fills the dashboard controls.
  creativeTargets: {
    mood: String,
    moodOptions: [String],
    style: String,
    styleOptions: [String],
    rationale: String,
  },
  productionConstraints: {
    budget: String,
    timeline: String,
    estimatedShootDays: Number,
    drivers: [String],
    rationale: String,
  },
  scenes: [sceneSchema],
  cameraSettings: cameraSettingsSchema,
  approvalLog: [{
    user: String,
    role: String,
    action: { type: String, enum: ['Approved', 'Revision Requested', 'Flagged'] },
    target: String,
    note: String,
    createdAt: { type: Date, default: Date.now },
  }],
}, { timestamps: true })

export default mongoose.model('Analysis', analysisSchema)
